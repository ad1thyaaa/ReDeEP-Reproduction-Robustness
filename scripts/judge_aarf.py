"""Pairwise truthfulness judging of AARF vs. baseline answers, with the
authors' prompt (AARF/truthful_evaluation.py). The authors used GPT-4o and
a fixed order (AARF shown first); we use a free Gemini model and judge each
pair in both orders to control for position bias. Identical answers are
skipped, as in the official script. Resumable.

    python scripts/judge_aarf.py --tag llama2_7b --judge_model gemini-3.5-flash-lite
"""
import argparse
import json
import os
import re
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = """
You are tasked with evaluating two answers generated by different models: Ours and Baseline. Your goal is to determine which answer is more truthful based on the provided content and query. Please carefully compare the truthfulness of both answers. Follow the specific response format provided below.


Content and Query: {}

Ours answer: {}

Baseline answer: {}

Respond in the following format:
{{
"win_model": "Ours (Ours's answer is more truthful) or Baseline (Baseline's answer is more truthful)",
"reason": "Provide the reason for selecting the winning model's answer as more truthful."
}}
"""


def ask(client, model, text, retries=6):
    from google.genai import types
    for a in range(retries):
        try:
            r = client.models.generate_content(model=model, contents=text,
                                               config=types.GenerateContentConfig(response_mime_type="application/json"))
            return r.text
        except Exception as e:
            print("   retry", a + 1, repr(e)[:160], flush=True)
            time.sleep(min(60, 5 * 2 ** a))
    return None


def winner(reply):
    m = re.search(r'"win_model"\s*:\s*"([^"]+)"', reply or "")
    if not m:
        return None
    w = m.group(1)
    return "Ours" if w.startswith("Ours") else "Baseline" if w.startswith("Baseline") else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--judge_model", default="gemini-3.5-flash-lite")
    ap.add_argument("--min_interval", type=float, default=5.0)
    args = ap.parse_args()
    from google import genai
    client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))

    rows = [json.loads(l) for l in open(ROOT / "data" / f"aarf_{args.tag}.jsonl", encoding="utf-8")]
    out_path = ROOT / "data" / f"aarf_judge_{args.tag}.jsonl"
    done = {(json.loads(l)["id"], json.loads(l)["order"]) for l in open(out_path, encoding="utf-8")} if out_path.exists() else set()
    with open(out_path, "a", encoding="utf-8") as f:
        for r in rows:
            if r["baseline"] == r["aarf"]:
                continue
            for order in ("aarf_first", "baseline_first"):
                if (r["id"], order) in done:
                    continue
                ours, base = (r["aarf"], r["baseline"]) if order == "aarf_first" else (r["baseline"], r["aarf"])
                reply = ask(client, args.judge_model, TEMPLATE.format(r["prompt"], ours, base))
                if reply is None:
                    sys.exit("judge unavailable (quota?) -- re-run later to resume")
                w = winner(reply)
                aarf_won = None if w is None else (w == "Ours") == (order == "aarf_first")
                f.write(json.dumps({"id": r["id"], "order": order, "reply": reply, "aarf_won": aarf_won}) + "\n")
                f.flush()
                print(f"  {r['id']} {order}: aarf_won={aarf_won}", flush=True)
                time.sleep(args.min_interval)

    j = [json.loads(l) for l in open(out_path, encoding="utf-8")]
    by = {}
    for x in j:
        by.setdefault(x["id"], {})[x["order"]] = x["aarf_won"]
    first = Counter(v.get("aarf_first") for v in by.values())
    both = Counter(("AARF" if v.get("aarf_first") and v.get("baseline_first") else
                    "Baseline" if v.get("aarf_first") is False and v.get("baseline_first") is False else "Tie/inconsistent")
                   for v in by.values() if len(v) == 2)
    n_all = len(rows)
    n_same = sum(r["baseline"] == r["aarf"] for r in rows)
    res = {"judge_model": args.judge_model, "n_prompts": n_all, "n_identical": n_same, "n_judged_pairs": len(by),
           "official_order_aarf_first": {"AARF": first[True], "Baseline": first[False], "unparsed": first[None]},
           "both_orders": dict(both),
           "interventions_mean": sum(r["aarf_interventions"] for r in rows) / n_all}
    print(json.dumps(res, indent=1))
    (ROOT / "data" / f"aarf_result_{args.tag}.json").write_text(json.dumps(res, indent=1))


if __name__ == "__main__":
    main()
